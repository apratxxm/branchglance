def current_user_sid() -> str:
    if os.name != "nt":
        return "S-1-5-21-0-0-0-1000"  # deterministic namespace for non-Windows tests only
    import ctypes
    from ctypes import wintypes
    advapi = ctypes.WinDLL("advapi32", use_last_error=True)
    kernel = ctypes.WinDLL("kernel32", use_last_error=True)
    kernel.GetCurrentProcess.restype = wintypes.HANDLE
    kernel.CloseHandle.argtypes = [wintypes.HANDLE]
    advapi.GetTokenInformation.argtypes = [wintypes.HANDLE, ctypes.c_int, ctypes.c_void_p,
                                          wintypes.DWORD, ctypes.POINTER(wintypes.DWORD)]
    advapi.GetTokenInformation.restype = wintypes.BOOL
    advapi.ConvertSidToStringSidW.argtypes = [ctypes.c_void_p, ctypes.POINTER(wintypes.LPWSTR)]
    advapi.ConvertSidToStringSidW.restype = wintypes.BOOL
    token = wintypes.HANDLE()
    advapi.OpenProcessToken.argtypes = [wintypes.HANDLE, wintypes.DWORD, ctypes.POINTER(wintypes.HANDLE)]
    advapi.OpenProcessToken.restype = wintypes.BOOL
    if not advapi.OpenProcessToken(kernel.GetCurrentProcess(), 0x0008, ctypes.byref(token)):
        raise ctypes.WinError(ctypes.get_last_error())
    try:
        size = wintypes.DWORD()
        advapi.GetTokenInformation(token, 1, None, 0, ctypes.byref(size))
        buffer = ctypes.create_string_buffer(size.value)
        if not advapi.GetTokenInformation(token, 1, buffer, size, ctypes.byref(size)):
            raise ctypes.WinError(ctypes.get_last_error())
        sid_pointer = ctypes.cast(buffer, ctypes.POINTER(ctypes.c_void_p))[0]
        text = wintypes.LPWSTR()
        if not advapi.ConvertSidToStringSidW(sid_pointer, ctypes.byref(text)):
            raise ctypes.WinError(ctypes.get_last_error())
        try:
            sid = text.value
        finally:
            kernel.LocalFree.argtypes = [ctypes.c_void_p]
            kernel.LocalFree(text)
        if not re.fullmatch(r"S-1-(?:\d+-)+\d+", sid):
            raise OSError("Current user SID is malformed")
        return sid
    finally:
        kernel.CloseHandle(token)


def mutex_name(purpose: str, sid: str | None = None) -> str:
    if purpose not in ("Install", "Instance"):
        raise ValueError("unknown mutex purpose")
    sid = current_user_sid() if sid is None else sid
    if not re.fullmatch(r"S-1-(?:\d+-)+\d+", sid):
        raise ValueError("invalid user SID")
    return f"Global\\Branchglance-{sid}-{purpose}"


def mutex_security_sddl(sid: str | None = None) -> str:
    sid = current_user_sid() if sid is None else sid
    if not re.fullmatch(r"S-1-(?:\d+-)+\d+", sid):
        raise ValueError("invalid user SID")
    return f"D:P(A;;GA;;;{sid})(A;;GA;;;SY)"


def _create_mutex_with_dacl(name: str, sddl: str, kernel, advapi):
    import ctypes
    from ctypes import wintypes
    advapi.ConvertStringSecurityDescriptorToSecurityDescriptorW.argtypes = [wintypes.LPCWSTR, wintypes.DWORD,
        ctypes.POINTER(ctypes.c_void_p), ctypes.POINTER(wintypes.DWORD)]
    advapi.ConvertStringSecurityDescriptorToSecurityDescriptorW.restype = wintypes.BOOL
    descriptor = ctypes.c_void_p()
    if not advapi.ConvertStringSecurityDescriptorToSecurityDescriptorW(sddl, 1, ctypes.byref(descriptor), None):
        raise ctypes.WinError(ctypes.get_last_error())
    class SECURITY_ATTRIBUTES(ctypes.Structure):
        _fields_ = [("nLength", wintypes.DWORD), ("lpSecurityDescriptor", ctypes.c_void_p),
                    ("bInheritHandle", wintypes.BOOL)]
    attrs = SECURITY_ATTRIBUTES(ctypes.sizeof(SECURITY_ATTRIBUTES), descriptor, False)
    kernel.CreateMutexW.argtypes = [ctypes.POINTER(SECURITY_ATTRIBUTES), wintypes.BOOL, wintypes.LPCWSTR]
    kernel.CreateMutexW.restype = ctypes.c_void_p
    handle = kernel.CreateMutexW(ctypes.byref(attrs), False, name)
    error = ctypes.get_last_error() if not handle else 0
    kernel.LocalFree.argtypes = [ctypes.c_void_p]
    kernel.LocalFree(descriptor)
    if not handle:
        if error == 5:
            kernel.OpenMutexW.argtypes = [wintypes.DWORD, wintypes.BOOL, wintypes.LPCWSTR]
            kernel.OpenMutexW.restype = ctypes.c_void_p
            handle = kernel.OpenMutexW(0x00100001, False, name)  # synchronize + modify-state
        if not handle:
            raise OSError(error or ctypes.get_last_error(), "CreateMutexW/OpenMutexW failed")
    return handle


def create_secured_mutex(name: str):
    """Create/open a global Branchglance mutex with the same user+SYSTEM DACL everywhere."""
    import ctypes
    if not isinstance(name, str) or not name.startswith("Global\\Branchglance-"):
        raise ValueError("invalid Branchglance mutex name")
    sid = current_user_sid()
    prefix = f"Global\\Branchglance-{sid}-"
    purpose = name[len(prefix):] if name.startswith(prefix) else ""
    if purpose not in ("Install", "Instance") and not re.fullmatch(r"Instance\.Test\.[0-9a-f]{32}", purpose):
        raise ValueError("mutex name is not scoped to the current user")
    kernel = ctypes.WinDLL("kernel32", use_last_error=True)
    advapi = ctypes.WinDLL("advapi32", use_last_error=True)
    return _create_mutex_with_dacl(name, mutex_security_sddl(sid), kernel, advapi)


