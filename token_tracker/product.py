_REPARSE = getattr(stat, "FILE_ATTRIBUTE_REPARSE_POINT", 0x400)


class StorageRedirectedError(RuntimeError):
    """A mutable product root, or something inside the WebView2 profile, is redirected."""


def _is_reparse(path: Path) -> bool:
    try:
        info = os.lstat(path)
    except OSError:
        return True
    if stat.S_ISLNK(info.st_mode):
        return True
    return bool(getattr(info, "st_file_attributes", 0) & _REPARSE)


def _entry_is_reparse(entry: os.DirEntry) -> bool:
    try:
        return entry.is_symlink() or bool(
            getattr(entry.stat(follow_symlinks=False), "st_file_attributes", 0) & _REPARSE)
    except OSError:
        return True


def _refuse_redirected_chain(anchor: Path, path: Path) -> None:
    """``anchor`` and each existing component from it down to ``path`` must be a plain directory."""
    anchor, path = Path(anchor), Path(path)
    try:
        relative = path.relative_to(anchor)
    except ValueError:
        raise StorageRedirectedError(f"{path} is outside the product data root {anchor}") from None
    current = anchor
    for part in ("", *relative.parts):
        current = current / part if part else current
        try:
            info = os.lstat(current)
        except FileNotFoundError:
            return  # nothing below a missing component can be redirected yet
        except OSError as exc:
            raise StorageRedirectedError(f"cannot inspect {current}: {exc}") from exc
        if stat.S_ISLNK(info.st_mode) or getattr(info, "st_file_attributes", 0) & _REPARSE:
            raise StorageRedirectedError(f"{current} is a junction or link")
        if not stat.S_ISDIR(info.st_mode):
            raise StorageRedirectedError(f"{current} is not a directory")


def _refuse_redirected_tree(root: Path) -> None:
    """No reparse point anywhere inside an existing profile tree; nothing is followed or modified."""
    pending = [Path(root)]
    while pending:
        directory = pending.pop()
        try:
            entries = list(os.scandir(directory))
        except FileNotFoundError:
            continue
        except OSError as exc:
            raise StorageRedirectedError(f"cannot inspect {directory}: {exc}") from exc
        for entry in entries:
            if _entry_is_reparse(entry):
                raise StorageRedirectedError(f"{entry.path} is a junction or link")
            if entry.is_dir(follow_symlinks=False):
                pending.append(Path(entry.path))


def validate_storage(*, frozen: bool | None = None, environ: Mapping[str, str] | None = None) -> None:
    """Refuse installed-product storage that is redirected (for example into TokenTracker).

    Checks the data root, the state root and the WebView2 storage, each with
    its directory chain from the data root, plus every entry inside an existing
    WebView2 profile. Read-only: a redirect target is never touched.
    Development checkouts use explicitly chosen roots and are not checked.
    """
    env = _environ(environ)
    root = product_root(frozen=frozen, environ=env)
    if root is None:
        return
    _refuse_redirected_chain(root, root)
    _refuse_redirected_chain(root, state_root(frozen=frozen, environ=env))
    webview = webview_storage_path(frozen=frozen, environ=env)
    _refuse_redirected_chain(root, webview)
    _refuse_redirected_tree(webview)


def storage_problem(*, frozen: bool | None = None, environ: Mapping[str, str] | None = None) -> str | None:
    try:
        validate_storage(frozen=frozen, environ=environ)
    except StorageRedirectedError as exc:
        return str(exc)
    return None


def _copy_plain_tree(source: Path, target: Path, *, create: bool = True) -> None:
    """Copy regular files and directories only; reparse points are skipped, never followed."""
    if create:
        target.mkdir()
    for entry in os.scandir(source):
        path = Path(entry.path)
        if _is_reparse(path):
            continue
        if entry.is_dir(follow_symlinks=False):
            _copy_plain_tree(path, target / entry.name)
        elif entry.is_file(follow_symlinks=False):
            with open(path, "rb") as src, open(target / entry.name, "wb") as dst:
                while chunk := src.read(1 << 20):
                    dst.write(chunk)


def prepare_webview_storage(destination: Path, legacy: Path | None = None) -> Path:
    """Return ``destination``, seeding it once from the legacy pywebview folder.

    The legacy folder is only read, never modified or deleted. A failed copy
    leaves ``destination`` absent so WebView2 starts clean rather than half-seeded.

    An existing destination that is, or contains, a junction or link raises
    :class:`StorageRedirectedError` and is left untouched. Seeding copies into
    a staging directory this call creates exclusively under a unique name; only
    that exact directory is ever cleaned up, and a collision is refused.
    """
    import shutil
    destination = Path(destination)
    if os.path.lexists(destination):
        if _is_reparse(destination) or not destination.is_dir():
            raise StorageRedirectedError(f"{destination} is a junction, link or file")
        _refuse_redirected_tree(destination)
        return destination
    if os.path.lexists(destination.parent) and _is_reparse(destination.parent):
        raise StorageRedirectedError(f"{destination.parent} is a junction or link")
    legacy = legacy_webview_path() if legacy is None else Path(legacy)
    try:
        if legacy.is_dir() and not _is_reparse(legacy):
            destination.parent.mkdir(parents=True, exist_ok=True)
            staging = destination.with_name(f"{destination.name}.copy-{uuid.uuid4().hex}")
            os.mkdir(staging)  # exclusive: an existing name raises and is never deleted
            try:
                _copy_plain_tree(legacy, staging, create=False)
                os.replace(staging, destination)
            except OSError:
                shutil.rmtree(staging, ignore_errors=True)  # only the directory created above
                raise
    except OSError:
        _LOG.warning("Could not seed WebView2 storage from the legacy folder", exc_info=True)
    return destination
